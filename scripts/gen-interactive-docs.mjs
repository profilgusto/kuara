#!/usr/bin/env node
/**
 * ─────────────────────────────────────────────────────────────────────────────
 * Kuara — Regenerate the interactive-widget catalogue in the authoring guide
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * The list of widgets an author may use, and each widget's parameters, lives in
 * `app/components/interactive/catalog.ts`. Hand-maintaining the same list in
 * docs/content-authoring-guide.md guarantees the two drift apart — and the
 * guide is what AI authors are told to follow literally, so a stale table
 * becomes broken content.
 *
 * This script rewrites the block between the markers
 *   <!-- BEGIN:interactive-catalog -->  …  <!-- END:interactive-catalog -->
 * and leaves the surrounding prose alone.
 *
 * Why esbuild? The catalogue is TypeScript. Rather than add a TS runner as a
 * dependency, we bundle it to a temporary .mjs and import that — the same
 * trick scripts/create-migration.sh uses for payload.config.ts.
 *
 * Usage (from the repo root):
 *   node scripts/gen-interactive-docs.mjs          # rewrite the guide
 *   node scripts/gen-interactive-docs.mjs --check  # fail if it would change
 * ─────────────────────────────────────────────────────────────────────────────
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CATALOG = path.join(REPO, "app/components/interactive/catalog.ts");
const GUIDE = path.join(REPO, "docs/content-authoring-guide.md");
const ESBUILD = path.join(REPO, "app/node_modules/.bin/esbuild");

const BEGIN = "<!-- BEGIN:interactive-catalog -->";
const END = "<!-- END:interactive-catalog -->";

const checkOnly = process.argv.includes("--check");

async function loadCatalog() {
  const dir = mkdtempSync(path.join(tmpdir(), "kuara-catalog-"));
  const out = path.join(dir, "catalog.mjs");
  try {
    execFileSync(
      ESBUILD,
      [
        CATALOG,
        "--bundle",
        "--format=esm",
        "--platform=node",
        "--log-level=error",
        `--outfile=${out}`,
      ],
      { stdio: ["ignore", "ignore", "inherit"] },
    );
    return await import(pathToFileURL(out).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Markdown-safe: the descriptions contain backticks and pipes. */
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

function renderWidget(meta, { mdxSnippet, typeTokens, defaultToken }) {
  const renderType = (spec) =>
    typeTokens(spec)
      .map((t) => "`" + t + "`")
      .join(" \\| ");
  const renderDefault = (spec) => {
    const token = defaultToken(spec);
    return token === null ? "\u2014" : "`" + token + "`";
  };

  const rows = Object.entries(meta.props).map(
    ([name, spec]) =>
      `| \`${name}\` | ${renderType(spec)} | ${renderDefault(spec)} | ${cell(spec.describe)} |`,
  );

  return [
    `#### \`${meta.id}\` — ${meta.title}`,
    "",
    cell(meta.description),
    "",
    "| Parameter | Type | Default | Description |",
    "|-----------|------|---------|-------------|",
    ...rows,
    "",
    "```mdx",
    mdxSnippet(meta),
    "```",
  ].join("\n");
}

const helpers = await loadCatalog();
const { catalog } = helpers;
const ids = Object.keys(catalog).sort();

const generated = [
  BEGIN,
  "",
  "<!-- Generated by scripts/gen-interactive-docs.mjs — do not edit by hand. -->",
  "",
  ...ids.map((id) => renderWidget(catalog[id], helpers)),
  "",
  END,
].join("\n");

const guide = readFileSync(GUIDE, "utf8");
const start = guide.indexOf(BEGIN);
const stop = guide.indexOf(END);
if (start === -1 || stop === -1) {
  console.error(`✗ markers ${BEGIN} / ${END} not found in ${GUIDE}`);
  process.exit(1);
}

const next = guide.slice(0, start) + generated + guide.slice(stop + END.length);

if (next === guide) {
  console.log(
    `✓ ${path.relative(REPO, GUIDE)} is up to date (${ids.length} widget(s))`,
  );
  process.exit(0);
}

if (checkOnly) {
  console.error(
    `✗ ${path.relative(REPO, GUIDE)} is stale — run: node scripts/gen-interactive-docs.mjs`,
  );
  process.exit(1);
}

writeFileSync(GUIDE, next);
console.log(
  `✓ regenerated ${ids.length} widget(s) in ${path.relative(REPO, GUIDE)}`,
);
